/**
 * 解析一类的原始文本为词条。
 *
 * @param raw 每行 `名称|别名1,别名2|提示` 的文本
 * @param cat 该文本所属分类
 * @returns 词条数组；空行忽略，名称为空的行忽略
 * @example parseLines('报纸|旧报纸\n', 'recyclable') // [{ name: '报纸', alias: ['旧报纸'], cat: 'recyclable', tip: '' }]
 */
export function parseLines(raw: string, cat: WasteCat): WasteItem[] {
  const out: WasteItem[] = []
  for (const line of raw.split('\n')) {
    const t = line.trim()
    if (!t) continue
    const [name, alias = '', tip = ''] = t.split('|')
    if (!name.trim()) continue
    out.push({
      name: name.trim(),
      alias: alias.split(',').map((s) => s.trim()).filter(Boolean),
      cat,
      tip: tip.trim(),
    })
  }
  return out
}

